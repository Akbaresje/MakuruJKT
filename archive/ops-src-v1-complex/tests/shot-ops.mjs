import { chromium } from 'playwright-core';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const errs = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 940 } });
page.setDefaultTimeout(6000);
page.on('pageerror', e => errs.push('desktop: ' + e.message));
page.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
await page.goto('file:///home/user/makuru-ops.html');
await page.waitForTimeout(600);
await page.screenshot({ path: 'shots-ops/01-gateway.png' });
await page.click('[data-act="enter"]');
await page.waitForTimeout(600);
await page.screenshot({ path: 'shots-ops/02-dashboard.png', fullPage: true });
await page.goto('file:///home/user/makuru-ops.html#/inventory');
await page.reload(); await page.waitForTimeout(500);
await page.screenshot({ path: 'shots-ops/03-inventory.png', fullPage: true });
await page.goto('file:///home/user/makuru-ops.html#/raw-materials');
await page.reload(); await page.waitForTimeout(500);
await page.selectOption('#prod-product', 'p-frz');
await page.fill('#prod-packs', '18');
await page.dispatchEvent('#prod-packs', 'input');
await page.waitForTimeout(250);
await page.screenshot({ path: 'shots-ops/04-raw-materials.png', fullPage: true });
await page.goto('file:///home/user/makuru-ops.html#/orders');
await page.reload(); await page.waitForTimeout(500);
await page.click('.row-click');
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots-ops/05-order-detail.png' });
await page.click('.dialog-head [data-act="modal-close"]');
await page.click('[data-act="tab"][data-tab="consignment"]');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots-ops/06-consignment.png', fullPage: true });
await page.click('[data-act="settle-modal"]');
await page.waitForTimeout(400);
await page.fill('[data-sold="p-siu"]', '3');
await page.dispatchEvent('[data-sold="p-siu"]', 'input');
await page.waitForTimeout(250);
await page.screenshot({ path: 'shots-ops/07-settlement.png' });
await page.click('.dialog-head [data-act="modal-close"]');
await page.goto('file:///home/user/makuru-ops.html#/dispatch');
await page.reload(); await page.waitForTimeout(600);
await page.screenshot({ path: 'shots-ops/08-dispatch.png', fullPage: true });
await page.goto('file:///home/user/makuru-ops.html#/finance');
await page.reload(); await page.waitForTimeout(600);
await page.screenshot({ path: 'shots-ops/09-finance.png', fullPage: true });
// mobile
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
m.on('pageerror', e => errs.push('mobile: ' + e.message));
await m.goto('file:///home/user/makuru-ops.html#/dashboard');
await m.waitForTimeout(600);
await m.screenshot({ path: 'shots-ops/10-m-dashboard.png' });
await m.goto('file:///home/user/makuru-ops.html#/inventory');
await m.waitForTimeout(500);
await m.screenshot({ path: 'shots-ops/11-m-inventory.png' });
console.log('errors:', errs.length, errs.slice(0, 4));
await browser.close();
