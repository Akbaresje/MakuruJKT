import { chromium } from 'playwright-core';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto('file:///home/user/index.html');
await page.waitForTimeout(900);
await page.screenshot({ path: 'shots/01-hero.png' });
await page.evaluate(() => document.querySelector('#katalog').scrollIntoView());
await page.waitForTimeout(700);
await page.screenshot({ path: 'shots/02-menu.png' });
await page.evaluate(() => document.querySelector('#po').scrollIntoView());
await page.waitForTimeout(700);
await page.screenshot({ path: 'shots/03-po.png' });
await page.evaluate(() => document.querySelector('#lokasi').scrollIntoView());
await page.waitForTimeout(700);
await page.screenshot({ path: 'shots/04-lokasi.png' });
await page.evaluate(() => document.querySelector('#openDashBtn').click());
await page.waitForTimeout(900);
await page.screenshot({ path: 'shots/05-dash.png', fullPage: true });
await page.evaluate(() => document.querySelector('.dash-nav button[data-view="orders"]').click());
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/06-orders.png' });
await page.evaluate(() => document.querySelector('#ordersBody tr').click());
await page.waitForTimeout(600);
await page.screenshot({ path: 'shots/07-sheet.png' });
console.log('errors:', errs.length, errs.slice(0,3));
await browser.close();
